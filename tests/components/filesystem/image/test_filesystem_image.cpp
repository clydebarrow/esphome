static void set_loop_time(uint32_t now) { LoopBlockingGuard clock(nullptr, LOG_STR("test"), now); }

class FilesystemImageProgress : public ::testing::TestWithParam<std::pair<const char *, runtime_image::ImageFormat>> {
 protected:
  void SetUp() override {
    this->disk_.setup();
    this->fs_.set_pool_sizes(1, 0);
    this->fs_.setup();
    this->fs_.files["/solid.png"] = std::vector<uint8_t>(PNG_SOLID, PNG_SOLID + sizeof(PNG_SOLID));
    this->fs_.files["/gradient.jpg"] = std::vector<uint8_t>(JPEG_GRADIENT, JPEG_GRADIENT + sizeof(JPEG_GRADIENT));
  }

  ram_disk::RamDisk disk_{512, 16};
  FakeFs fs_{&disk_};
};

// Progress starts at 0, is reported at most every 100 ms, and reaches 100% before the image is finished
TEST_P(FilesystemImageProgress, ReportsProgressUntilLoaded) {
  const auto [path, format] = GetParam();
  FilesystemImage image(&this->fs_, path, 0, 0, format, image::IMAGE_TYPE_RGB565, image::TRANSPARENCY_OPAQUE, nullptr,
                        256, false);
  std::vector<std::pair<float, size_t>> reports;
  int finished = 0;
  int errors = 0;
  size_t reports_when_finished = 0;
  image.add_on_load_progress_callback(
      [&reports](float progress, size_t bytes_read) { reports.emplace_back(progress, bytes_read); });
  image.add_on_load_finished_callback([&]() {
    finished++;
    reports_when_finished = reports.size();
  });
  image.add_on_error_callback([&errors]() { errors++; });

  uint32_t now = 1000;
  set_loop_time(now);
  image.update();
  ASSERT_EQ(reports.size(), 1u);
  EXPECT_EQ(reports[0].first, 0.0f);

  int passes = 0;
  for (; passes < 10000 && finished + errors == 0; passes++) {
    now += 50;
    set_loop_time(now);
    image.loop();
  }

  ASSERT_EQ(finished, 1);
  EXPECT_EQ(errors, 0);
  const size_t size = this->fs_.files[path].size();
  EXPECT_EQ(reports.back(), std::make_pair(100.0f, size));
  EXPECT_EQ(reports_when_finished, reports.size()) << "100% is reported before on_load_finished";
  EXPECT_TRUE(std::is_sorted(reports.begin(), reports.end()));
  // A report every 100 ms of a 50 ms loop, plus the start and the end
  EXPECT_LE(reports.size(), static_cast<size_t>(passes / 2 + 2));
}

